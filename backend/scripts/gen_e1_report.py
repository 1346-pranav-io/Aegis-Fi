import glob
import json
import pathlib
import statistics as st

from aegis.ml.registry import verify_manifest

f = sorted(glob.glob("results/e1_*.json"))[-1]
r = json.load(open(f))
stamp = pathlib.Path(f).stem[3:]
art = pathlib.Path("artefacts") / stamp
info = []
for m in sorted(art.glob("*.manifest.json")):
    man, _ = verify_manifest(m)
    info.append((man.name, man.sha256[:12], man.mlflow_run_id))
b1 = r["systems"]["B1_xgboost"]
runs = b1["runs"]


def ms(part, key):
    v = [x[part][key] for x in runs]
    return st.mean(v), st.stdev(v)


def rk(part, k, which):
    return st.mean([x[part][which][k] for x in runs])


b0 = r["systems"]["B0_rules"]
ab = r["systems"]["B1_intrinsic_only"]
cal = b1["calibration_isotonic_on_validation"]
L = []
L.append("# E1 - Detection baselines, run 1 (measured)\n")
L.append(
    f"Generated by script from `experiments/results/{pathlib.Path(f).name}`; every number below is copied from that file. MLflow run `{info[0][2]}`. Artefacts verified against manifests: "
    + ", ".join(f"{n} (sha256 {h}...)" for n, h, _ in info)
    + ".\n"
)
L.append(
    f"- Dataset: {r['dataset']} (synthetic). Split hash `{r['split_hash'][:16]}...` (D-24). Dataset manifest `{r['dataset_manifest_hash'][:16]}...`. Feature set `{r['feature_set_version']}`. Code hash `{r['code_hash'][:16]}...`."
)
L.append(
    "- Unit: transaction (D-25). Parts: "
    + "; ".join(f"{k} n={v['n']:,} pos={v['pos']:,}" for k, v in r["parts"].items())
    + "."
)
L.append(
    f"- Single run, 3 XGBoost seeds ({', '.join(str(x['seed']) for x in runs)}); no confidence intervals beyond seed spread. Test and stress touched once. Early stopping and seed selection used validation, so validation numbers are optimistically biased.\n"
)
L.append(
    "## Ranking quality\n| System | Window | PR-AUC | ROC-AUC | base rate | recall@1000 | precision@100 |\n|---|---|---|---|---|---|---|"
)
for p in ("validation", "test"):
    m = b0["metrics"][p]
    L.append(
        f"| B0 rules v1 | {p} | {m['pr_auc']:.5f} | {m['roc_auc']:.3f} | {m['base_rate']:.5f} | {m['recall_at_k']['1000']:.3f} | {m['precision_at_k']['100']:.3f} |"
    )
for p in ("validation", "test"):
    a = ms(p, "pr_auc")
    ro = ms(p, "roc_auc")
    base = runs[0][p]["base_rate"]
    L.append(
        f"| B1 XGBoost (mean +- sd, 3 seeds) | {p} | {a[0]:.4f} +- {a[1]:.4f} | {ro[0]:.3f} +- {ro[1]:.3f} | {base:.5f} | {rk(p, '1000', 'recall_at_k'):.3f} | {rk(p, '100', 'precision_at_k'):.3f} |"
    )
for p in ("validation", "test"):
    m = ab[p]
    L.append(
        f"| B1 intrinsic-only (seed 11, diagnostic) | {p} | {m['pr_auc']:.4f} | {m['roc_auc']:.3f} | {m['base_rate']:.5f} | {m['recall_at_k']['1000']:.3f} | {m['precision_at_k']['100']:.3f} |"
    )
L.append(
    "\nStress slice (Sep 11-18; 1,108 rows, 59.1% positive; NOT comparable with the rows above):\n"
)
L.append("| System | PR-AUC | ROC-AUC |\n|---|---|---|")
m = b0["metrics"]["stress"]
L.append(f"| B0 | {m['pr_auc']:.3f} | {m['roc_auc']:.3f} |")
a = ms("stress", "pr_auc")
ro = ms("stress", "roc_auc")
L.append(f"| B1 (mean +- sd) | {a[0]:.3f} +- {a[1]:.3f} | {ro[0]:.3f} +- {ro[1]:.3f} |")
m = ab["stress"]
L.append(f"| B1 intrinsic-only | {m['pr_auc']:.3f} | {m['roc_auc']:.3f} |")
L.append(
    "\n## B1 per seed (PR-AUC validation -> test)\n"
    + "\n".join(
        f"- seed {x['seed']}: {x['validation']['pr_auc']:.4f} -> {x['test']['pr_auc']:.4f} ({x['best_iteration'] + 1} trees)"
        for x in runs
    )
)
L.append(
    "\n## B0 rules on the test window\n| Rule | fires | precision | recall |\n|---|---|---|---|"
)
for k, v in b0["per_rule_test"].items():
    L.append(
        f"| {k} | {v['fires_test']:,} | {('n/a' if v['precision_test'] is None else format(v['precision_test'], '.4f'))} | {v['recall_test']:.4f} |"
    )
L.append(
    "\nThresholds frozen from unlabeled train features: "
    + json.dumps(
        {k: (round(v, 1) if isinstance(v, float) else v) for k, v in b0["rule_pack"].items()}
    )
    + "\n"
)
L.append(
    "## Calibration (isotonic fitted on validation; D-06)\n| Window | ECE of raw XGBoost output (NOT a probability) | ECE calibrated | mean calibrated | actual base rate |\n|---|---|---|---|---|"
)
for p in ("test", "stress"):
    c = cal[p]
    L.append(
        f"| {p} | {c['raw_score_ece_NOT_A_PROBABILITY']:.4f} | {c['calibrated_ece']:.4f} | {c['mean_calibrated']:.4f} | {c['base_rate']:.4f} |"
    )
imp = list(b1["gain_importance_selected"].items())[:6]
L.append("\n## Top gain features (selected seed)\n" + ", ".join(f"{k} ({v:.0f})" for k, v in imp))
open("../docs/research/E1_RESULTS_RUN1.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))
